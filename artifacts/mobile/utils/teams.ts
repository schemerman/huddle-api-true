// Letters that don't split into a base letter + accent, so accent stripping misses them.
const FOLDS: Record<string, string> = { "ø": "o", "æ": "ae", "œ": "oe", "ß": "ss", "ł": "l", "đ": "d", "ı": "i" };

export function normalizeTeamName(name: string): string {
  const key = name
    .toLowerCase()
    .replace(/[øæœßłđı]/g, (ch) => FOLDS[ch] ?? ch)
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/&/g, " and ")
    .replace(/\b(afc|fc)\b/g, " ")
    .replace(/[^a-z0-9]/g, "");
  return ALIASES[key] ?? key;
}

const crestCache = new Map<string, string | null>();

export const getCrestUrl = (team?: string | null): string | null => {
  if (!team) return null;
  if (crestCache.has(team)) return crestCache.get(team)!;
  const key = normalizeTeamName(team);
  let id: number | undefined = ESPN_CREST_IDS[key];
  if (id === undefined && key.length >= 5) {
    // "feyenoord" vs "feyenoordrotterdam": take the longest name that one starts with the other.
    let best = "";
    for (const candidate of Object.keys(ESPN_CREST_IDS)) {
      if (candidate.length >= 5 && candidate.length > best.length && (candidate.startsWith(key) || key.startsWith(candidate))) best = candidate;
    }
    if (best) id = ESPN_CREST_IDS[best];
  }
  const url = id === undefined ? null : `https://a.espncdn.com/i/teamlogos/soccer/500/${id}.png`;
  crestCache.set(team, url);
  return url;
};
